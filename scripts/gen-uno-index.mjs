#!/usr/bin/env node
/*
 * Generate public/uno-index.js from the LibreOffice IDL reference.
 *
 * The Wasm build ships only the interface type registry (CoreReflection), so
 * modules and services cannot be enumerated at runtime. This script crawls the
 * published namespace pages and records the interfaces and services of every
 * com.sun.star module, which lets describe("com.sun.star.sheet") list them.
 *
 * Usage: node scripts/gen-uno-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'public', 'uno-index.js');
const BASE = 'https://api.libreoffice.org/docs/idl/ref/';
const START = 'namespacecom_1_1sun_1_1star.html';

const decodeModule = (file) =>
  file.replace(/^namespace/, '').replace(/\.html$/, '').split('_1_1').join('.');

async function get(file) {
  const res = await fetch(BASE + file);
  if (!res.ok) throw new Error(`${file} -> HTTP ${res.status}`);
  return res.text();
}

function extract(page, nsFile) {
  const marker = nsFile.replace(/^namespace/, '').replace(/\.html$/, '');
  const interfaces = new Set();
  const services = new Set();
  const modules = new Set();

  const re = /href="(interface|service)([^"#]*)\.html">([^<]+)<\/a>/g;
  let m;
  while ((m = re.exec(page))) {
    const [, kind, rest, label] = m;
    if (rest.indexOf('#') !== -1 || label.includes('::') || label === 'More...') continue;
    // Only members of this module, not cross-references from signatures.
    if (!rest.startsWith(marker + '_1_1')) continue;
    const name = rest.slice(marker.length + '_1_1'.length);
    if (!name || name.includes('_1_1')) continue;
    (kind === 'interface' ? interfaces : services).add(name);
  }

  const reMod = /href="(namespace[^"#]*\.html)"/g;
  while ((m = reMod.exec(page))) {
    if (m[1] !== nsFile) modules.add(m[1]);
  }

  return {
    interfaces: [...interfaces].sort(),
    services: [...services].sort(),
    modules: [...modules],
  };
}

const seen = new Set();
const queue = [START];
const index = {};

while (queue.length) {
  const file = queue.shift();
  if (seen.has(file)) continue;
  seen.add(file);
  process.stderr.write(`[uno-index] ${file}\n`);
  let page;
  try {
    page = await get(file);
  } catch (err) {
    process.stderr.write(`[uno-index] skip: ${err.message}\n`);
    continue;
  }
  const { interfaces, services, modules } = extract(page, file);
  const name = decodeModule(file);
  if (interfaces.length || services.length) {
    index[name] = { interfaces, services };
  }
  for (const mod of modules) if (!seen.has(mod)) queue.push(mod);
  await new Promise((r) => setTimeout(r, 60));
}

const header = `// Generated by scripts/gen-uno-index.mjs from ${BASE}\n` +
  `// Do not edit by hand. Regenerate to pick up a new LibreOffice release.\n`;
fs.writeFileSync(OUT,
  header + 'export const UNO_INDEX = ' + JSON.stringify(index, null, 1) + ';\n');

const modulesCount = Object.keys(index).length;
const typeCount = Object.values(index).reduce((n, m) => n + m.interfaces.length + m.services.length, 0);
console.log(`[uno-index] wrote ${path.relative(process.cwd(), OUT)}: ` +
  `${modulesCount} modules, ${typeCount} interfaces/services`);
